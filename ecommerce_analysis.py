top_profit_products = df.groupby('Product_Name')['Profit'].sum().sort_values(ascending=False).head(10)
plt.figure(figsize=(10, 6))
plt.barh(top_profit_products.index, top_profit_products.values)
plt.title('Top 10 Products by Profit')
plt.xlabel('Total Profit')
plt.ylabel('Product Name')
plt.gca().invert_yaxis()
plt.tight_layout()
plt.show()

region_analysis = df.groupby('Region')[['Total_Sales', 'Profit']].sum()
region_analysis.plot(kind='bar', figsize=(9, 6))
plt.title('Sales vs Profit by Region')
plt.xlabel('Region')
plt.ylabel('Amount')
plt.xticks(rotation=0)
plt.legend(['Sales', 'Profit'])
plt.tight_layout()
plt.show()

