avg_discount_profit = df.groupby('Discount_Percent')['Profit'].mean()

plt.figure(figsize=(10, 6))
plt.plot([f"{d}%" for d in avg_discount_profit.index], avg_discount_profit.values, marker='o', color='crimson', linewidth=2)

plt.title('Impact of Discount on Average Profit')
plt.xlabel('Discount Percentage')
plt.ylabel('Average Profit per Order ($)')

plt.grid(True, linestyle='--', alpha=0.6)
plt.tight_layout()
plt.show()